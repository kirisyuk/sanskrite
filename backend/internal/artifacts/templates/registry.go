// GetSystemTemplate returns a system template by ID
func GetSystemTemplate(id string) (*models.ArtifactTemplate, error) {
	template, ok := SystemTemplates[id]
	if !ok {
		return nil, fmt.Errorf("system template not found: %s", id)
	}
	return template, nil
}

// ListSystemTemplates returns all system templates
func ListSystemTemplates() []*models.ArtifactTemplate {
	templates := make([]*models.ArtifactTemplate, 0, len(SystemTemplates))
	for _, t := range SystemTemplates {
		templates = append(templates, t)
	}
	return templates
}

// ListSystemTemplatesByCategory returns system templates for a specific category
func ListSystemTemplatesByCategory(category string) []*models.ArtifactTemplate {
	templates := make([]*models.ArtifactTemplate, 0)
	for _, t := range SystemTemplates {
		if t.Category == category {
			templates = append(templates, t)
		}
	}
	return templates
}
