package main

import (
	"context"
	"encoding/json"
	"flag"
	"log"
	"os"
	"strings"
	"time"

	"github.com/igorkirisyuk/sanskrite/internal/gcp"
	"github.com/igorkirisyuk/sanskrite/internal/models"
)

// Seeds market segment normalization dictionary into Firestore.
//
// Collection: horizon_market_segment_dict, DocID: version (default "v1").
//
// Usage:
//
//	go run ./cmd/tools/horizon_seed_market_segment_dict --project <gcp-project> --version v1
func main() {
	ctx := context.Background()

	projectID := flag.String("project", os.Getenv("GCP_PROJECT_ID"), "GCP project id (defaults to $GCP_PROJECT_ID)")
	version := flag.String("version", "v1", "dictionary version doc id (default v1)")
	fromJSON := flag.String("from-json", "", "Optional: path to JSON file with MarketSegmentDictionary (auto-generated by python). If set, this payload is uploaded.")
	flag.Parse()

	if *projectID == "" {
		log.Fatal("--project is required (or set GCP_PROJECT_ID)")
	}

	fsClient, err := gcp.NewFirestoreClient(ctx, *projectID)
	if err != nil {
		log.Fatalf("firestore init failed: %v", err)
	}
	defer fsClient.Close()

	now := time.Now().UTC()
	doc := &models.MarketSegmentDictionary{}
	if strings.TrimSpace(*fromJSON) != "" {
		b, err := os.ReadFile(strings.TrimSpace(*fromJSON))
		if err != nil {
			log.Fatalf("failed to read --from-json file: %v", err)
		}
		// Allow either a full document or just the rule payload without metadata.
		if err := json.Unmarshal(b, doc); err != nil {
			// Try to support a file that contains only the dict body.
			// (Still must match MarketSegmentDictionary JSON field names.)
			var tmp models.MarketSegmentDictionary
			if err2 := json.Unmarshal(b, &tmp); err2 != nil {
				log.Fatalf("failed to parse --from-json: %v", err)
			}
			*doc = tmp
		}
	} else {
		// Built-in starter defaults (safe baseline).
		doc = &models.MarketSegmentDictionary{
			SegmentChannelDomains: []string{
				"b2b", "b2c", "commercial", "industrial", "consumer",
				"public-sector", "public", "government", "gov", "b2g",
			},
			SegmentDomainAliases: map[string]string{
				"public":             "public-sector",
				"government":         "public-sector",
				"gov":                "public-sector",
				"b2g":                "public-sector",
				"fintech":            "finance",
				"financial-services": "finance",
				"industrials":        "industrial",
			},
			SegmentVerticalAliases: map[string]string{
				"retail-banking": "banking",
				"cryptocurrency": "crypto",
			},
			SegmentVerticalFamilies: map[string]string{
				// Finance family
				"banking":            "finance",
				"investment":         "finance",
				"asset-management":   "finance",
				"private-equity":     "finance",
				"venture-capital":    "finance",
				"financial-services": "finance",
				"fintech":            "finance",
				"insurance":          "finance",
				"payments":           "finance",
				"crypto":             "finance",
				// Technology family
				"software":       "technology",
				"it-services":    "technology",
				"cybersecurity":  "technology",
				"semiconductors": "technology",
				"electronics":    "technology",
				// Energy family
				"oil-and-gas": "energy",
				"utilities":   "energy",
				"renewables":  "energy",
				// Nuance placeholders (can be refined later via SegmentNormRules)
				"casinos":  "entertainment",
				"gambling": "entertainment",
			},
			SegmentNormRules: map[string]models.MarketSegmentNormRuleData{},
		}
	}

	// Always stamp metadata.
	doc.Version = *version
	doc.UpdatedAt = now

	ref := fsClient.Client().Collection("horizon_market_segment_dict").Doc(*version)
	// Use Set() with merge=false semantics (overwrite) to keep it deterministic.
	if _, err := ref.Set(ctx, doc); err != nil {
		log.Fatalf("failed to write market segment dictionary: %v", err)
	}
	log.Printf("Seeded horizon_market_segment_dict/%s (updatedAt=%s)", *version, now.Format(time.RFC3339))
}
