#!/usr/bin/env bash
set -euo pipefail

# Fetch _TEST secrets from GCP Secret Manager and write a local .env.test
# Usage:
#   ./scripts/pull-test-secrets.sh [-p|--project h1horizon-488615]
# Load after creation:
#   set -a; source .env.test; set +a

PROJECT="h1horizon-488615"
while [[ $# -gt 0 ]]; do
  case "$1" in
    -p|--project) PROJECT="$2"; shift 2;;
    *) echo "Unknown arg: $1" >&2; exit 2;;
  esac
done

if ! command -v gcloud >/dev/null 2>&1; then
  echo "gcloud not found" >&2
  exit 1
fi

echo "Using project: $PROJECT"
gcloud config set project "$PROJECT" >/dev/null

fetch_secret() {
  local name="$1"
  gcloud secrets versions access latest --secret="$name" 2>/dev/null || true
}

OPENAI_API_KEY_TEST_VAL="$(fetch_secret OPENAI_API_KEY_TEST)"
ANTHROPIC_API_KEY_TEST_VAL="$(fetch_secret ANTHROPIC_API_KEY_TEST)"
DEEPSEEK_API_KEY_TEST_VAL="$(fetch_secret DEEPSEEK_API_KEY_TEST)"
GROK_API_KEY_TEST_VAL="$(fetch_secret GROK_API_KEY_TEST)"
GEMINI_API_KEY_TEST_VAL="$(fetch_secret GEMINI_API_KEY_TEST)"
TAVILY_API_KEY_TEST_VAL="$(fetch_secret TAVILY_API_KEY_TEST)"

cat > .env.test <<EOF
# Generated by scripts/pull-test-secrets.sh
OPENAI_API_KEY_TEST=${OPENAI_API_KEY_TEST_VAL}
ANTHROPIC_API_KEY_TEST=${ANTHROPIC_API_KEY_TEST_VAL}
DEEPSEEK_API_KEY_TEST=${DEEPSEEK_API_KEY_TEST_VAL}
GROK_API_KEY_TEST=${GROK_API_KEY_TEST_VAL}
GEMINI_API_KEY_TEST=${GEMINI_API_KEY_TEST_VAL}
TAVILY_API_KEY_TEST=${TAVILY_API_KEY_TEST_VAL}

GCP_PROJECT_ID=${PROJECT}
VERTEX_LOCATION=us-central1
EOF

echo "Wrote .env.test"


