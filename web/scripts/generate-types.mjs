#!/usr/bin/env node

import { compileFromFile } from 'json-schema-to-typescript';
import { promises as fs } from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const schemasDir = path.join(__dirname, '../src/types/schemas');
const outputFile = path.join(__dirname, '../src/types/generated.ts');

async function generateTypes() {
  const files = await fs.readdir(schemasDir);
  const schemaFiles = files.filter(f => f.endsWith('.schema.json'));
  
  const types = [];
  const typeMapping = {}; // Map from schema file name to generated interface name
  const header = `/* eslint-disable */
/**
 * This file was automatically generated by json-schema-to-typescript.
 * DO NOT MODIFY IT BY HAND. Instead, modify the source JSON Schema files,
 * and run 'npm run gen:types' to regenerate this file.
 */

`;

  for (const file of schemaFiles) {
    const filePath = path.join(schemasDir, file);
    const typeName = path.basename(file, '.schema.json');
    
    console.log(`Generating types for ${file}...`);
    
    try {
      const ts = await compileFromFile(filePath, {
        bannerComment: '',
        style: {
          semi: true,
          singleQuote: true,
          trailingComma: 'es5',
        },
        unknownAny: false,
        declareExternallyReferenced: true,
      });
      
      // Extract the generated interface name from the output
      const interfaceMatch = ts.match(/export interface (\w+)/);
      if (interfaceMatch) {
        typeMapping[typeName] = interfaceMatch[1];
      }
      
      types.push(ts);
    } catch (error) {
      console.error(`Error generating types for ${file}:`, error.message);
      process.exit(1);
    }
  }
  
  // Add convenient type aliases at the end
  const aliases = Object.entries(typeMapping)
    .map(([name, fullName]) => `export type ${name} = ${fullName};`)
    .join('\n');
  
  const content = header + types.join('\n') + '\n\n// Convenient type aliases\n' + aliases + '\n';
  await fs.writeFile(outputFile, content, 'utf-8');
  
  console.log(`✅ Successfully generated types to ${outputFile}`);
}

generateTypes().catch(error => {
  console.error('Fatal error:', error);
  process.exit(1);
});

